vi.mock('@xyflow/react',async original=>({...await original<object>(),useReactFlow:()=>({fitView:vi.fn()})}));
vi.mock('react-i18next', () => ({ useTranslation: () => ({ t: (key: string) => key }) }));
vi.mock('@/hooks/use-media-query', () => ({ useMediaQuery: () => true }));
vi.mock('@/features/canvas/Canvas', () => ({ Canvas: () => <div>画布内容</div> }));
vi.mock('@/features/canvas/ui/CanvasRunPanel', () => ({ CanvasRunPanel: () => null }));
vi.mock('@/features/freezone/AssetLibraryPanel', () => ({ AssetLibraryPanel: () => null }));
vi.mock('@/features/freezone/CanvasDebugPanel', () => ({ CanvasDebugPanel: () => null }));
vi.mock('@/features/canvas/ui/NodeReplaceDragPreview', () => ({ NodeReplaceDragPreview: () => null }));
vi.mock('@/features/direction-references/DirectionReferenceEntry', () => ({ DirectionReferenceEntry: () => null }));
