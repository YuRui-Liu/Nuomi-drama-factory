afterEach(() => vi.unstubAllGlobals());
it('passes managed identity through the real Shell, Dock, Panel and Picker without a default connection', async () => {
  localStorage.clear(); useAuthStore.setState({ username: 'alice' });
  HTMLElement.prototype.scrollTo = vi.fn();
  const urls: string[] = [];
  const closeSocket = vi.fn();
  class Socket {
    static OPEN = 1;
    close = closeSocket; send = vi.fn();
    constructor(url: string) { urls.push(url); }
  }
  vi.stubGlobal('WebSocket', Socket);
  http.get.mockImplementation((url: string) => ({ json: async () => ({ data: url.includes('canvas_id=canvas-a') ? [{ id: 'thread-a', title: 'A会话', canvas_id: 'canvas-a' }] : [] }) }));
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  const project = { id: 'project-one', creation_mode: 'agent_canvas_v1' } as SupertaleProjectSummary;
  render(<QueryClientProvider client={client}><FreezoneShell project={project} canvasId="canvas-a" managedWorkspace /></QueryClientProvider>);
  fireEvent.click(screen.getByRole('button', { name: 'freezone.chat.toggle' }));
  await screen.findByRole('option', { name: 'A会话' }, { timeout: 5000 });
  expect(http.get).toHaveBeenCalledWith('api/v1/chat/conversations?project=project-one&canvas_id=canvas-a', expect.anything());
  expect(urls).toEqual([]); expect(http.post).not.toHaveBeenCalled();
  fireEvent.change(screen.getByLabelText('切换助手会话'), { target: { value: 'thread-a' } });
  await waitFor(() => expect(urls).toHaveLength(1));
  expect(Object.fromEntries(new URL(urls[0]).searchParams)).toEqual({ project_id: 'project-one', canvas_id: 'canvas-a', conversation_id: 'thread-a' });
  expect(screen.getByText('画布内容')).toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: 'freezone.chat.close' }));
  expect(closeSocket).not.toHaveBeenCalled();
  expect(http.post).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('button', { name: 'freezone.chat.toggle' }));
  expect(screen.getByLabelText('切换助手会话')).toHaveValue('thread-a');
  expect(urls).toHaveLength(1);
});
